game_logs = []
for idx, row in df_nba.iterrows():
    # Number of clutch games played in this player-season (roughly 1 clutch game per 2.1 clutch TSA)
    n_games = int(np.clip(np.round(row['clutch_tsa'] / 2.08 + np.random.normal(0, 2.0)), 18, 52))

    for g in range(n_games):
        # Between-game schedule rest: 0 days (Back-to-Back: 17%), 1 day (59%), 2+ days (24%)
        sched_draw = np.random.rand()
        if sched_draw < 0.17:
            days_rest = "0 Days (Back-to-Back)"
            b2b_penalty = -1.65
        elif sched_draw < 0.76:
            days_rest = "1 Day Rest"
            b2b_penalty = 0.0
        else:
            days_rest = "2+ Days Rest"
            b2b_penalty = +0.55

        # In-game 4Q rest regime conditioned on player-season rest tendency
        p_rest = 0.62 if row['got_4q_rest_window'] == 1 else 0.18
        r_draw = np.random.rand()
        if r_draw < p_rest:
            stint_regime = "Full 4Q Rest (>=2.0m)"
            stint_bonus = +1.75
        elif r_draw < p_rest + 0.20:
            stint_regime = "Short Breather (0.5-1.9m)"
            stint_bonus = -0.15
        else:
            stint_regime = "No 4Q Rest (Unbroken 12m)"
            stint_bonus = -1.85

        game_pcwi = np.clip(row['pcwi'] + (-2.2 if stint_bonus > 0 else 1.8) + (-1.0 if b2b_penalty > 0 else 1.5) + np.random.normal(0, 2.5), 88.0, 118.0) if (stint_bonus := stint_bonus) else row['pcwi']

        # Game-level clutch delta TS% and 3P%
        cliff_excess = max(0.0, game_pcwi - k_star)
        g_delta_ts = (
            row['true_skill_latent']
            - 0.12 * (game_pcwi - 95.0)
            - 0.56 * cliff_excess
            + stint_bonus
            + b2b_penalty
            + np.random.normal(0, 6.5)
        )
        g_delta_3p = 0.65 * row['true_skill_latent'] + 1.35 * (-0.12*(game_pcwi - 95.0) - 0.56*cliff_excess + stint_bonus + b2b_penalty) + np.random.normal(0, 7.2)

        game_logs.append({
            'player_name': row['player_name'],
            'team': row['team'],
            'season': row['season'],
            'days_rest': days_rest,
            'stint_regime': stint_regime,
            'game_pcwi': game_pcwi,
            'game_delta_ts': g_delta_ts,
            'game_delta_3p': g_delta_3p,
            'is_unbroken_no_rest': int(stint_regime == "No 4Q Rest (Unbroken 12m)"),
            'is_b2b_no_rest': int(days_rest == "0 Days (Back-to-Back)")
        })

