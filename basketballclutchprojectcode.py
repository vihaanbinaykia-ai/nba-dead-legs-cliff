print(f"Structural Break F-Test: F = {f_stat_cliff:.2f}, p = {p_val_cliff:.4e}")

# CELL 3: Empirical Bayes (James-Stein) Shrinkage & Fatigue-Adjusted Clutch Efficiency (FACE)

# 1. Calculate Expected Clutch TS% Differential given Pre-Clutch Workload & 4Q Rest State
X_full = sm.add_constant(df_nba[['pcwi', 'pcwi_above_cliff', 'got_4q_rest_window']])
model_full = sm.WLS(df_nba['delta_ts_pct'], X_full, weights=df_nba['clutch_tsa']).fit()

df_nba['expected_fatigue_delta_ts'] = model_full.predict(X_full)

# Calculate the "Clutch Fatigue Tax" (CFT): how many TS% points workload & stint fatigue cost the player
# Relative to a fresh baseline starter (PCWI = 95.0, with 4Q rest window = 1)
X_fresh_ref = np.array([1.0, 95.0, 0.0, 1.0])
fresh_baseline_pred = float(np.dot(X_fresh_ref, model_full.params))
df_nba['clutch_fatigue_tax_ts'] = df_nba['expected_fatigue_delta_ts'] - fresh_baseline_pred

# 2. Raw Workload-Adjusted Clutch Residual (Raw WACR)
df_nba['raw_residual_ts'] = df_nba['delta_ts_pct'] - df_nba['expected_fatigue_delta_ts']

# 3. Empirical Bayes (James-Stein) Shrinkage to eliminate small-sample clutch noise
# Within-player binomial/shooting variance constant sigma^2_within ~ 780, Between-player true skill variance tau^2 ~ 3.6
KAPPA_SHRINKAGE = 55.0  # Equivalent sample size prior (in True Shooting Attempts)
df_nba['eb_reliability_weight'] = df_nba['clutch_tsa'] / (df_nba['clutch_tsa'] + KAPPA_SHRINKAGE)

# FACE (Fatigue-Adjusted Clutch Efficiency): Empirical Bayes shrunken residual above workload expectation
df_nba['FACE_metric'] = df_nba['eb_reliability_weight'] * df_nba['raw_residual_ts']

# Aggregate across 2021-2026 for Named NBA Stars to create Leaderboard
star_summary = df_nba[df_nba['is_named_star'] == 1].groupby(['player_name', 'team']).agg(
    seasons=('season', 'count'),
    total_clutch_tsa=('clutch_tsa', 'sum'),
    mean_pcwi=('pcwi', lambda x: round(np.mean(x), 1)),
    rest_window_pct=('got_4q_rest_window', lambda x: round(np.mean(x)*100, 1)),
    raw_delta_ts=('delta_ts_pct', lambda x: round(np.mean(x), 2)),
    fatigue_tax_ts=('clutch_fatigue_tax_ts', lambda x: round(np.mean(x), 2)),
    FACE_score=('FACE_metric', lambda x: round(np.mean(x), 2)),
    true_skill=('true_skill_latent', 'first')
).reset_index()

# Multi-season reliability boost for career leaderboard
star_summary['career_FACE'] = np.round(
    (star_summary['total_clutch_tsa'] / (star_summary['total_clutch_tsa'] + 65.0)) *
    (star_summary['raw_delta_ts'] - star_summary['fatigue_tax_ts']), 2
)

# Correlation with true latent clutch skill: Raw Delta TS% vs FACE
r_raw, _ = stats.pearsonr(star_summary['raw_delta_ts'], star_summary['true_skill'])
r_face, _ = stats.pearsonr(star_summary['career_FACE'], star_summary['true_skill'])

print("=== CELL 3 OUTPUT: EMPIRICAL BAYES 'FACE' METRIC VALIDATION ===")
print(f"Correlation with True Latent Clutch Skill: Raw Clutch Delta TS% r = {r_raw:.3f} vs Empirical Bayes FACE r = {r_face:.3f}")
print(f"Variance Reduction from James-Stein Shrinkage: {(1 - df_nba['FACE_metric'].var()/df_nba['raw_residual_ts'].var())*100:.1f}% noise removed\n")

print("=== TABLE 1A: TOP 10 NBA CLOSERS BY FATIGUE-ADJUSTED CLUTCH EFFICIENCY (FACE, 2021-2026) ===")
top10_face = star_summary.sort_values(by='career_FACE', ascending=False).head(10)
print(top10_face[['player_name', 'team', 'total_clutch_tsa', 'mean_pcwi', 'rest_window_pct', 'raw_delta_ts', 'fatigue_tax_ts', 'career_FACE']].to_string(index=False))

print("\n=== TABLE 1B: HIGH-WORKLOAD STARS MOST PENALIZED BY FATIGUE TAX (OVERWORKED CLOSERS) ===")
overworked = star_summary.sort_values(by='fatigue_tax_ts', ascending=True).head(8)
print(overworked[['player_name', 'team', 'mean_pcwi', 'rest_window_pct', 'raw_delta_ts', 'fatigue_tax_ts', 'career_FACE']].to_string(index=False))

# CELL 4: Coaching Stint Management Audit — The Value of a 2-Minute Early-4Q Rest Window
rest_cohort = df_nba[df_nba['got_4q_rest_window'] == 1]
unbroken_cohort = df_nba[df_nba['got_4q_rest_window'] == 0]

t_ts, p_ts = stats.ttest_ind(rest_cohort['delta_ts_pct'], unbroken_cohort['delta_ts_pct'], equal_var=False)
